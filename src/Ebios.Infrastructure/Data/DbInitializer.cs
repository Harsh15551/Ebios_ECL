                    ""Status"" character varying(50) NOT NULL DEFAULT 'Verified',
                    ""IsFlagged"" boolean NOT NULL DEFAULT false,
                    ""CreatedAt"" timestamp with time zone NOT NULL
                );
                CREATE INDEX IF NOT EXISTS ""IX_AttendanceLogs_EmpCode"" ON ""AttendanceLogs""(""EmpCode"");
                CREATE INDEX IF NOT EXISTS ""IX_AttendanceLogs_LogDate"" ON ""AttendanceLogs""(""LogDate"");
                CREATE INDEX IF NOT EXISTS ""IX_AttendanceLogs_SerialNumber"" ON ""AttendanceLogs""(""SerialNumber"");
