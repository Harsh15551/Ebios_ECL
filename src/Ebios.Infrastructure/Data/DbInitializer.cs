                    ""SerialNumber"" character varying(100) NOT NULL,
                    ""DeviceName"" character varying(150) NOT NULL,
                    ""Direction"" character varying(20) NOT NULL,
                    ""DeviceType"" character varying(50),
                    ""TimeZone"" character varying(100),
                    ""SubAreaId"" integer NOT NULL REFERENCES ""SubAreas""(""Id"") ON DELETE CASCADE,
