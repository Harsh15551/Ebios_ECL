                ALTER TABLE ""Devices"" ADD COLUMN IF NOT EXISTS ""ActivationCode"" character varying(100) DEFAULT '0';
                ALTER TABLE ""Employees"" ADD COLUMN IF NOT EXISTS ""AdditionalSubAreaIds"" text;

